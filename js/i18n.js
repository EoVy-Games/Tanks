let LANG = (() => {
  try { const v = JSON.parse(localStorage.getItem('tdb_lang')); if (v === 'fr' || v === 'en') return v; } catch (e) { }
  return /^fr\b/i.test(navigator.language || '') ? 'fr' : 'en';
})();

// tr('key', {name: 'Bob'}, 'fallback') → translated text with placeholders filled in
function tr(key, vars, fallback) {
  let s = I18N[LANG][key];
  if (s == null) s = I18N.fr[key];
  if (s == null) s = fallback != null ? fallback : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}
// tn('key', n) → picks 'key.one' or 'key.other'
function tn(key, n, vars) {
  const one = LANG === 'fr' ? Math.abs(n) < 2 : n === 1;
  return tr(key + (one ? '.one' : '.other'), Object.assign({ n }, vars));
}
// Fills every element marked data-i18n (text), data-i18n-aria, data-i18n-title, data-i18n-ph (placeholder).
function applyStaticText(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', tr(el.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-title]').forEach(el => el.setAttribute('title', tr(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-ph]').forEach(el => el.setAttribute('placeholder', tr(el.dataset.i18nPh)));
  document.documentElement.lang = LANG;
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', tr('meta.desc'));
}
